// Приведение формулировок замечаний к сравнимому виду: одно и то же замечание
// проверяющие пишут по-разному («нет ведомости ссылочных документов» /
// «отсутствует ведомость ссылочных и прилагаемых документов»).

const STOP = new Set(
  (
    'а без более бы был была были было в во все всё вы где да для до его ее её если есть же за ' +
    'и из или им их к как ко ли либо между на над не ни но о об от по под при про с со так ' +
    'также то только у уже что чтобы это этот эта эти лист листа листе листах листов см стр ' +
    'п пп пункт рис табл таблица таблице указано указан приведено приведен выполнено выполнен'
  ).split(' '),
);

// «нет» выражают по-разному — сводим к одному слову
const MISSING = /^(?:отсутств|нет$|не(?:_?)указ|не(?:_?)привед|не(?:_?)показ|не(?:_?)обознач)/;

// окончания — от длинных к коротким; основа не короче четырёх букв
const ENDINGS = [
  'иями', 'ями', 'ами', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'ией', 'иях',
  'ах', 'ях', 'ых', 'их', 'ов', 'ев', 'ей', 'ой', 'ий', 'ый', 'ая', 'яя', 'ое', 'ее', 'ые', 'ие',
  'ую', 'юю', 'ом', 'ем', 'ам', 'ям', 'ия', 'ии', 'ию', 'ья', 'ье', 'ьи', 'ть', 'ет', 'ит',
  'ут', 'ют', 'ат', 'ят', 'ен', 'на', 'ны', 'но', 'а', 'я', 'о', 'е', 'ы', 'и', 'у', 'ю', 'ь', 'й',
];
const STEM_MAX = 7;

/** Основа русского слова: срезать до двух окончаний («итоговое» → «итогов» → «итог»), не длиннее семи букв. */
export function stem(word: string): string {
  let w = word;
  for (let pass = 0; pass < 2; pass += 1) {
    const ending = ENDINGS.find((e) => w.length - e.length >= 4 && w.endsWith(e));
    if (!ending) break;
    w = w.slice(0, -ending.length);
  }
  return w.slice(0, STEM_MAX);
}

/**
 * Слова замечания для сравнения: нижний регистр, ё → е, без чисел, марок и
 * размеров (в каждом альбоме свои), без служебных слов; «отсутствует»,
 * «не указан» и подобные → «нет».
 */
export function tokens(text: string): string[] {
  const words = text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/не\s+(указ|привед|показ|обознач)/g, 'не_$1')
    // «не равен», «не совпадает», «не соответствует», «не сходится», «расходится с» — одно и то же
    .replace(/не\s+(?:равн|равен|совпад|соответств|сход)[а-я]*|расходится|расходятся/g, 'несовпад')
    .split(/[^a-zа-я0-9_]+/)
    .filter(Boolean);
  const out: string[] = [];
  for (const word of words) {
    if (/\d/.test(word)) continue;
    if (MISSING.test(word)) {
      out.push('нет');
      continue;
    }
    if (word.length < 3 || STOP.has(word)) continue;
    out.push(stem(word));
  }
  return out;
}

/**
 * Документ нормы без пункта: «СП 63.13330.2018, п. 10.3.14» → «СП 63.13330.2018».
 * Нужен, чтобы замечания по одному документу тянулись друг к другу.
 */
export function normDocument(norm: string): string {
  const match = /(ГОСТ\s*Р?|СП|СНиП|СанПиН)\s*[\d.\-–]*\d/i.exec(norm.replace(/ё/g, 'е'));
  return match ? match[0].replace(/\s+/g, ' ').replace(/–/g, '-').toUpperCase().trim() : '';
}

/** Ссылки на листы, позиции и марки — убрать из текста-образца: в записи они не нужны. */
export function stripSheetRefs(text: string): string {
  // \b в JavaScript не видит границ кириллических слов — граница через (?<!\p{L})
  return text
    .replace(/\s*\((?:л|лист|листы|стр)\.?\s*[\d,\s–-]+\)/giu, '')
    .replace(/(?<!\p{L})(?:на\s+)?(?:л|лист(?:е|ах|ы)?)\.?\s*\d+(?:\s*[,–-]\s*\d+)*/giu, '')
    .replace(/\s{2,}/g, ' ')
    .replace(/\s+([,.;:])/g, '$1')
    .trim();
}
